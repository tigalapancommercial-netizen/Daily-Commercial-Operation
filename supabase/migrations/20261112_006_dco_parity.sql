-- ---------- BACKUP & ARSIP (archivePreview_, backup_, wipe_) ----------
create or replace function dco.archive_where(tbl text) returns text language sql immutable set search_path = pg_catalog, pg_temp as $$
select 'not (($1 <> '''' and x.tanggal < $1) or ($2 <> '''' and x.tanggal > $2))' $$;
create or replace function dco.archive_types(p_types text[]) returns text[] language plpgsql immutable set search_path = pg_catalog, pg_temp as $$
declare t text; outp text[] := '{}';
begin
  foreach t in array coalesce(p_types, '{}') loop
    if upper(t) not in ('MASALAH','TUGAS','CEKLIS','DSO','VISIT','VISIT_ISSUE','JADWAL') then raise exception 'Jenis data tidak valid'; end if;
    outp := outp || upper(t);
  end loop;
  if coalesce(array_length(outp, 1), 0) = 0 then raise exception 'Jenis data tidak valid'; end if;
  return outp;
end $$;

create or replace function public.dco_archive_preview(p_token text, p_types text[], p_from text, p_to text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); t text; n int; b int; counts jsonb := '{}'; blocked jsonb := '{}'; total int := 0;
  f text := coalesce(p_from, ''); tt text := coalesce(p_to, '');
begin
  perform dco.must_master(me);
  if f <> '' and tt <> '' and f > tt then raise exception 'Tanggal Dari tidak boleh melebihi Sampai'; end if;
  foreach t in array dco.archive_types(p_types) loop
    execute format('select count(*) from dco.%I x where %s', dco.tbl(t), dco.archive_where(dco.tbl(t))) into n using f, tt;
    counts := counts || jsonb_build_object(t, n); total := total + n;
    if t in ('MASALAH','TUGAS','VISIT_ISSUE') then
      execute format('select count(*) from dco.%I x where %s and x.status not in (''Selesai'',''Dibatalkan'')', dco.tbl(t), dco.archive_where(dco.tbl(t))) into b using f, tt;
      blocked := blocked || jsonb_build_object(t, b);
    end if;
  end loop;
  return jsonb_build_object('counts', counts, 'blocked', blocked, 'total', total, 'from', f, 'to', tt, 'willRemove', total);
end $$;

create or replace function public.dco_archive_rows(p_token text, p_types text[], p_from text, p_to text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); t text; res jsonb; outp jsonb := '{}'; f text := coalesce(p_from, ''); tt text := coalesce(p_to, '');
begin
  perform dco.must_master(me);
  if f <> '' and tt <> '' and f > tt then raise exception 'Rentang tanggal salah'; end if;
  foreach t in array dco.archive_types(p_types) loop
    execute format('select coalesce(jsonb_agg(to_jsonb(x) - ''_seq'' - ''_created'' order by x._seq), ''[]'') from dco.%I x where %s', dco.tbl(t), dco.archive_where(dco.tbl(t)))
      into res using f, tt;
    outp := outp || jsonb_build_object(t, res);
  end loop;
  return outp;
end $$;

-- Hapus data aktif secara atomik. p_ids = {TIPE:[id,...]} (mode arsip: hanya ID yang sudah ter-backup) atau null (wipe per rentang)
create or replace function public.dco_archive_delete(p_token text, p_types text[], p_from text, p_to text, p_ids jsonb,
  p_block_open boolean, p_collect_photos boolean, p_confirm text default '') returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); t text; tbl text; ids text[]; n int; b int; deleted jsonb := '{}'; paths text[] := '{}'; rr jsonb;
  f text := coalesce(p_from, ''); tt text := coalesce(p_to, ''); w text;
begin
  perform dco.must_master(me);
  if f <> '' and tt <> '' and f > tt then raise exception 'Rentang tanggal salah'; end if;
  if p_ids is null and coalesce(p_confirm, '') <> 'HAPUS PERMANEN' then raise exception 'Ketik HAPUS PERMANEN untuk konfirmasi'; end if;
  foreach t in array dco.archive_types(p_types) loop
    tbl := dco.tbl(t); perform pg_advisory_xact_lock(hashtext('dco:' || tbl));
    w := dco.archive_where(tbl);
    if p_ids is not null then
      select coalesce(array_agg(v), '{}') into ids from jsonb_array_elements_text(coalesce(p_ids->t, '[]')) v;
      w := w || ' and x.id = any($3)';
    end if;
    if p_block_open and t in ('MASALAH','TUGAS','VISIT_ISSUE') then
      execute format('select count(*) from dco.%I x where %s and x.status not in (''Selesai'',''Dibatalkan'')', tbl, w) into b using f, tt, ids;
      if b > 0 then raise exception 'Tidak boleh mengarsipkan % % yang masih open/pending. Selesaikan dulu atau pilih mode Salin saja.', b, t; end if;
    end if;
    n := 0;
    for rr in execute format('delete from dco.%I x where %s returning to_jsonb(x)', tbl, w) using f, tt, ids loop
      n := n + 1;
      if p_collect_photos then paths := paths || dco.photo_paths(rr); end if;
    end loop;
    if p_ids is not null and n <> coalesce(array_length(ids, 1), 0) then
      raise exception 'Verifikasi arsip % gagal (% dari % baris). Tidak ada data yang dihapus.', t, n, coalesce(array_length(ids, 1), 0);
    end if;
    deleted := deleted || jsonb_build_object(t, n);
  end loop;
  return jsonb_build_object('deleted', deleted, 'photos', to_jsonb(dco.grant_trash(paths)));
end $$;

create or replace function public.dco_backup_save(p_token text, p_nama text, p_info jsonb, p_b64 text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); bin bytea; nid bigint; h text;
begin
  perform dco.must_master(me);
  if coalesce(p_nama, '') = '' then raise exception 'Nama backup kosong'; end if;
  bin := decode(p_b64, 'base64');
  if length(bin) > 25 * 1024 * 1024 then raise exception 'File backup terlalu besar (maks 25 MB). Perkecil rentang tanggal.'; end if;
  h := encode(sha256(bin), 'hex');
  insert into dco.backups(nama, dibuat, oleh, info, isi, sha256) values (p_nama, dco.now_s(), me->>'nama', coalesce(p_info, '{}'), bin, h) returning id into nid;
  return jsonb_build_object('id', nid, 'sha256', h, 'size', length(bin));
end $$;
create or replace function public.dco_backup_list(p_token text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token);
begin
  perform dco.must_master(me);
  return (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'nama', nama, 'tgl', dibuat, 'oleh', oleh, 'size', length(isi), 'info', info) order by id desc), '[]') from dco.backups);
end $$;
create or replace function public.dco_backup_get(p_token text, p_id bigint) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); b dco.backups;
begin
  perform dco.must_master(me);
  select * into b from dco.backups where id = p_id;
  if not found then raise exception 'Backup tidak ditemukan'; end if;
  return jsonb_build_object('nama', b.nama, 'sha256', b.sha256, 'b64', translate(encode(b.isi, 'base64'), E'\n', ''));
end $$;
create or replace function public.dco_backup_delete(p_token text, p_id bigint) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token);
begin
  perform dco.must_master(me);
  delete from dco.backups where id = p_id;
  return jsonb_build_object('ok', true);
end $$;
