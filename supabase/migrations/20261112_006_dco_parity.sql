-- ---------- STORAGE FOTO ----------
-- Bucket publik "dco-foto" (setara file Drive "siapa saja yang punya link"): nama file acak 128-bit, tidak bisa ditebak/didaftar.
-- Upload hanya dengan tiket dari dco_upload_ticket; hapus hanya untuk file yang diizinkan server (photo_trash).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('dco-foto', 'dco-foto', true, 3145728, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists dco_foto_insert on storage.objects;
create policy dco_foto_insert on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'dco-foto' and public.dco_ticket_ok(name));
drop policy if exists dco_foto_select on storage.objects;
create policy dco_foto_select on storage.objects for select to anon, authenticated
  using (bucket_id = 'dco-foto' and (public.dco_ticket_ok(name) or public.dco_trash_ok(name)));
drop policy if exists dco_foto_delete on storage.objects;
create policy dco_foto_delete on storage.objects for delete to anon, authenticated
  using (bucket_id = 'dco-foto' and public.dco_trash_ok(name));

