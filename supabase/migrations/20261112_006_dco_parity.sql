-- BACA DATA (readAll_ + pembatasan role). Filter opsional: from, to, toko, tanggal, ids[], pending(validasi kosong)
create or replace function public.dco_rows(p_token text, p_type text, p_filter jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); t text := upper(coalesce(p_type, '')); tbl text := dco.tbl(p_type);
  is_mgr boolean := (me->>'is_mgr')::boolean; is_master boolean := (me->>'is_master')::boolean;
  f jsonb := coalesce(p_filter, '{}'::jsonb); w text := 'true'; cols text[]; sel text := 'to_jsonb(x) - ''_seq'' - ''_created'''; res jsonb;
  ids text[];
begin
  if tbl is null then raise exception 'Tipe data tidak dikenal: %', p_type; end if;
  if t = 'USERS' then
    if is_master then
      return (select coalesce(jsonb_agg(jsonb_build_object('username', username, 'role', role, 'toko', toko, 'nama', nama, 'email', email) order by _seq), '[]') from dco.users);
    end if;
    return (select coalesce(jsonb_agg(jsonb_build_object('username', username, 'role', role, 'toko', 'SEMUA', 'nama', nama, 'email', '') order by _seq), '[]')
              from dco.users where role in ('SPV','MASTER'));
  end if;
  if t = 'CONFIG' then return (select coalesce(jsonb_agg(jsonb_build_object('key', key, 'value', value) order by key), '[]') from dco.config); end if;
  if t = 'TOKO' then return (select coalesce(jsonb_agg(jsonb_build_object('nama', nama, 'area', area, 'aktif', aktif) order by _seq), '[]') from dco.toko); end if;
  if t = 'VISIT_ISSUE' then perform dco.must_mgr(me); end if;
  cols := dco.data_cols(tbl);
  if not is_mgr then
    if t = 'RUTIN' then w := w || ' and (x.toko = ''SEMUA'' or x.toko = '''' or $1 = any(string_to_array(x.toko, ''|'')))';
    elsif 'toko' = any(cols) then w := w || ' and x.toko = $1'; end if;
    if t = 'VISIT' then sel := 'jsonb_build_object(''id'',x.id,''tanggal'',x.tanggal,''toko'',x.toko,''final_score'',x.final_score,''rating'',x.rating,''validasi'',x.validasi)'; end if;
  elsif coalesce(f->>'toko', '') not in ('', 'SEMUA') and 'toko' = any(cols) then w := w || ' and x.toko = $4';
  end if;
  if 'tanggal' = any(cols) then
    if coalesce(f->>'from', '') <> '' then w := w || ' and x.tanggal >= $2'; end if;
    if coalesce(f->>'to', '') <> '' then w := w || ' and x.tanggal <= $3'; end if;
    if coalesce(f->>'tanggal', '') <> '' then w := w || ' and x.tanggal = $5'; end if;
  end if;
  if jsonb_typeof(f->'ids') = 'array' then
    select array_agg(v) into ids from jsonb_array_elements_text(f->'ids') v;
    w := w || ' and x.id = any($6)';
  end if;
  if coalesce((f->>'pending')::boolean, false) and 'validasi' = any(cols) then w := w || ' and x.validasi = '''''; end if;
  execute format('select coalesce(jsonb_agg(%s order by x._seq), ''[]''::jsonb) from dco.%I x where %s', sel, tbl, w)
    into res using me->>'toko', f->>'from', f->>'to', f->>'toko', f->>'tanggal', coalesce(ids, '{}');
  return res;
end $$;

-- SIMPAN DATA (add_/update_/bulk_/ceklisSet_/rutinSave_/jadwalSave_/visitSave_/issueUpdate_/defSave_/cfgSave_/tokoSave_)
-- Aturan role ditegakkan di server: STORE hanya data tokonya, hanya kolom STORE_EDIT, tidak bisa mengubah data tervalidasi.
create or replace function public.dco_save(p_token text, p_type text, p_rows jsonb, p_mode text default 'upsert') returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); t text := upper(coalesce(p_type, '')); tbl text := dco.tbl(p_type);
  is_mgr boolean := (me->>'is_mgr')::boolean; is_master boolean := (me->>'is_master')::boolean;
  pk text := 'id'; cols text[]; store_edit text[] := '{}'; r jsonb; cur jsonb; nw jsonb; k text; idv text;
  td text := dco.today(); nows text := dco.now_s(); outp jsonb := '[]'::jsonb; mode text := lower(coalesce(p_mode, 'upsert'));
begin
  if t not in ('MASALAH','TUGAS','CEKLIS','RUTIN','JADWAL','VISIT','VISIT_ISSUE','FORM_DEF','VISIT_DEF','CONFIG','TOKO') then
    raise exception 'Tipe tidak diizinkan: %', p_type; end if;
  if t in ('FORM_DEF','VISIT_DEF','CONFIG','TOKO') then perform dco.must_master(me); end if;
  if t in ('RUTIN','JADWAL','VISIT','VISIT_ISSUE') then perform dco.must_mgr(me); end if;
  if t = 'CONFIG' then pk := 'key'; elsif t = 'TOKO' then pk := 'nama'; end if;
  if p_rows is null then p_rows := '[]'::jsonb; elsif jsonb_typeof(p_rows) <> 'array' then p_rows := jsonb_build_array(p_rows); end if;
  if jsonb_array_length(p_rows) > 2000 then raise exception 'Maksimal 2000 baris per simpan'; end if;
  cols := dco.data_cols(tbl);
  store_edit := case t
    when 'MASALAH' then array['tanggal','sesi','pemimpin','peserta','kategori','masalah','akar','solusi','pic','due_date','prioritas','status','progress','tgl_selesai','update','link_bukti','foto_id']
    when 'TUGAS' then array['status','progress','tgl_selesai','catatan','foto_id']
    when 'CEKLIS' then array['status','catatan','foto_id'] else '{}'::text[] end;
  perform pg_advisory_xact_lock(hashtext('dco:' || tbl));
  for r in select value from jsonb_array_elements(p_rows) loop
    if jsonb_typeof(r) <> 'object' then raise exception 'Format data salah'; end if;
    r := (select coalesce(jsonb_object_agg(e.key, to_jsonb(dco.jtext(e.value))), '{}'::jsonb) from jsonb_each(r) e where e.key = any(cols));
    if r ? 'foto_id' and r->>'foto_id' <> '' and not dco.valid_photo(r->>'foto_id') then r := r || jsonb_build_object('foto_id', ''); end if;
    idv := nullif(btrim(coalesce(r->>pk, '')), '');
    cur := null;
    if idv is not null then
      execute format('select to_jsonb(x) - ''_seq'' - ''_created'' from dco.%I x where %I = $1 for update', tbl, pk) into cur using idv;
    elsif t = 'CEKLIS' then
      select to_jsonb(x) - '_seq' - '_created' into cur from dco.ceklis x
       where x.tanggal = coalesce(r->>'tanggal', '') and x.rutin_id = coalesce(r->>'rutin_id', '')
         and x.toko = case when is_mgr then coalesce(r->>'toko', '') else me->>'toko' end for update;
    end if;
    if mode = 'insert' and cur is not null then raise exception 'Data sudah ada: %', idv; end if;
    if mode = 'update' and cur is null then raise exception 'Data tidak ditemukan: %', coalesce(idv, ''); end if;

    if not is_mgr then
      if cur is not null then
        if cur->>'toko' is distinct from me->>'toko' then raise exception 'Bukan data toko Anda'; end if;
        if cur->>'validasi' = 'Y' then
          if t = 'CEKLIS' then raise exception 'Sudah divalidasi SPV'; else raise exception 'Sudah divalidasi SPV, tidak bisa diubah toko'; end if;
        end if;
        nw := cur;
        foreach k in array store_edit loop
          if r ? k then nw := nw || jsonb_build_object(k, r->k); end if;
        end loop;
      else
        nw := r || jsonb_build_object('toko', me->>'toko', 'validasi', '', 'validasi_oleh', '', 'validasi_tgl', '');
        if t in ('MASALAH','TUGAS') then nw := nw || jsonb_build_object('dibuat_oleh', me->>'nama'); end if;
      end if;
      if t = 'CEKLIS' then
        if coalesce(nw->>'tanggal', '') !~ '^\d{4}-\d{2}-\d{2}$' or nw->>'tanggal' < dco.add_days(td, -1) then
          raise exception 'Checklist hanya bisa diisi untuk hari ini / kemarin'; end if;
        if coalesce(nw->>'rutin_id', '') = '' then raise exception 'Routine tidak dikenal'; end if;
      end if;
    else
      nw := coalesce(cur, '{}'::jsonb) || r;
      if t = 'VISIT' then
        if cur is not null and cur->>'validasi' = 'Approved' and not is_master then raise exception 'Visit sudah diapprove Manager'; end if;
        if not is_master then
          nw := nw || jsonb_build_object('validasi', coalesce(cur->>'validasi', ''), 'validasi_oleh', coalesce(cur->>'validasi_oleh', ''), 'validasi_tgl', coalesce(cur->>'validasi_tgl', ''));
        end if;
      elsif t = 'VISIT_ISSUE' then
        if cur is not null and cur->>'validasi' = 'Y' and not is_master then raise exception 'Issue tervalidasi, hanya Master dapat mengubah'; end if;
      elsif t = 'JADWAL' then
        if cur is not null and cur->>'pic' is distinct from me->>'nama' and not is_master then raise exception 'Hanya pembuat jadwal atau Master yang bisa mengubah'; end if;
      end if;
    end if;

    -- jam centang checklist ditentukan jam server (WITA)
    if t = 'CEKLIS' and r ? 'status' and (cur is null or cur->>'status' is distinct from nw->>'status') then
      nw := nw || jsonb_build_object('jam', case when nw->>'status' = 'Selesai' then dco.hm() else '' end);
    end if;
    -- stempel update oleh server
    if 'update_tgl' = any(cols) then nw := nw || jsonb_build_object('update_tgl', nows); end if;
    if 'update_oleh' = any(cols) then
      nw := nw || jsonb_build_object('update_oleh', case when is_mgr and r->>'update_oleh' in ('SYNC_SOURCE','MIGRASI') then r->>'update_oleh' else me->>'nama' end);
    end if;
    if coalesce(nw->>pk, '') = '' then
      if t in ('CONFIG','TOKO') then raise exception 'Kunci data kosong'; end if;
      nw := nw || jsonb_build_object('id', dco.next_id(t, nw));
    end if;
    perform dco.upsert_row(tbl, pk, nw);
    execute format('select to_jsonb(x) - ''_seq'' - ''_created'' from dco.%I x where %I = $1', tbl, pk) into nw using nw->>pk;
    outp := outp || jsonb_build_array(nw);
  end loop;
  return outp;
end $$;

-- HAPUS DATA (bulk_ hapus, dsoHapus_, rutinHapus_, jadwalHapus_, visitHapus_, defHapus_)
create or replace function public.dco_delete(p_token text, p_type text, p_ids text[]) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); t text := upper(coalesce(p_type, '')); tbl text := dco.tbl(p_type);
  is_mgr boolean := (me->>'is_mgr')::boolean; is_master boolean := (me->>'is_master')::boolean;
  idv text; cur jsonb; deleted text[] := '{}'; paths text[] := '{}'; linked int := 0; rr jsonb;
begin
  if t not in ('MASALAH','TUGAS','CEKLIS','DSO','RUTIN','JADWAL','VISIT','FORM_DEF','VISIT_DEF') then raise exception 'Tipe hapus tidak diizinkan: %', p_type; end if;
  if t in ('RUTIN','JADWAL','VISIT') then perform dco.must_mgr(me); end if;
  if t in ('FORM_DEF','VISIT_DEF') then perform dco.must_master(me); end if;
  if coalesce(array_length(p_ids, 1), 0) = 0 then raise exception 'Tidak ada data terpilih'; end if;
  perform pg_advisory_xact_lock(hashtext('dco:' || tbl));
  foreach idv in array p_ids loop
    execute format('select to_jsonb(x) - ''_seq'' - ''_created'' from dco.%I x where id = $1 for update', tbl) into cur using idv;
    if cur is null then
      if t = 'DSO' then raise exception 'Laporan tidak ditemukan';
      elsif t = 'JADWAL' then raise exception 'Jadwal tidak ditemukan';
      elsif t = 'VISIT' then raise exception 'Data tidak ditemukan'; end if;
      continue;
    end if;
    if t in ('MASALAH','TUGAS','CEKLIS') and not is_mgr then
      if cur->>'toko' is distinct from me->>'toko' or cur->>'validasi' = 'Y' then continue; end if;  -- toko hanya boleh hapus miliknya yg belum divalidasi
    elsif t = 'DSO' and not is_mgr then
      if cur->>'toko' is distinct from me->>'toko' or cur->>'validasi' = 'Approved' then
        raise exception 'Tidak bisa dihapus (bukan toko Anda / sudah di-approve)'; end if;
    elsif t = 'JADWAL' then
      if cur->>'pic' is distinct from me->>'nama' and not is_master then raise exception 'Hanya pembuat jadwal atau Master yang bisa menghapus'; end if;
    elsif t = 'VISIT' then
      if cur->>'validasi' = 'Approved' and not is_master then raise exception 'Sudah di-approve Manager, hanya Master yang bisa menghapus'; end if;
      if exists(select 1 from dco.visit_issue i where i.visit_id = idv and i.status not in ('Selesai','Dibatalkan')) then
        raise exception 'Selesaikan issue Pending Matter terlebih dahulu sebelum menghapus visit'; end if;
      select count(*) into linked from dco.visit_issue i where i.visit_id = idv;
    end if;
    execute format('delete from dco.%I where id = $1', tbl) using idv;
    deleted := deleted || idv;
    if t in ('MASALAH','TUGAS','CEKLIS','DSO') then paths := paths || dco.photo_paths(cur); end if;
  end loop;
  return jsonb_build_object('jumlah', coalesce(array_length(deleted, 1), 0), 'ids', to_jsonb(deleted),
    'photos', to_jsonb(dco.grant_trash(paths)), 'linkedIssues', linked);
end $$;

-- DAILY STORE OPERATION — submit (dsoSubmit_), SLA kirim dihitung jam server WITA
create or replace function public.dco_dso_submit(p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); is_mgr boolean := (me->>'is_mgr')::boolean; cfg jsonb := dco.cfg(); frm jsonb;
  tgl text; tk text; jaw jsonb := '{}'::jsonb; e record; kurang text; cur dco.dso; nw jsonb; menit int; bm text[]; bmenit int; sla text;
  td text := dco.today(); nows text := dco.now_s();
begin
  select f into frm from jsonb_array_elements(coalesce(cfg->'dsoForms', '[]')) f where f->>'id' = p->>'form' limit 1;
  if frm is null then raise exception 'Form tidak dikenal'; end if;
  tgl := coalesce(nullif(p->>'tanggal', ''), td);
  if tgl !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Tanggal tidak valid'; end if;
  tk := case when is_mgr then coalesce(p->>'toko', '') else me->>'toko' end;
  if tk = '' or tk = 'SEMUA' then raise exception 'Pilih toko'; end if;
  if is_mgr and not exists(select 1 from dco.toko where nama = tk) then raise exception 'Toko tidak tersedia'; end if;
  if jsonb_typeof(p->'jawaban') = 'object' then
    for e in select key, value from jsonb_each(p->'jawaban') loop
      if dco.valid_photo(dco.jtext(e.value)) then jaw := jaw || jsonb_build_object(e.key, dco.jtext(e.value)); end if;
    end loop;
  end if;
  select string_agg(d.label, ', ' order by d._seq) into kurang from dco.form_def d
   where d.form = p->>'form' and d.aktif <> 'N' and d.wajib <> 'N' and coalesce(jaw->>d.id, '') = '';
  if kurang is not null then raise exception 'Foto wajib belum lengkap: %', kurang; end if;
  perform pg_advisory_xact_lock(hashtext('dco:dso'));
  select * into cur from dco.dso where tanggal = tgl and toko = tk and form = p->>'form' for update;
  if found and cur.validasi = 'Approved' and not is_mgr then raise exception 'Laporan sudah di-approve SPV, tidak bisa diubah'; end if;
  menit := extract(hour from now() at time zone 'Asia/Makassar')::int * 60 + extract(minute from now() at time zone 'Asia/Makassar')::int;
  bm := regexp_match(coalesce(frm->>'batas', ''), '^(\d{1,2}):(\d{2})');
  bmenit := case when bm is null then -1 else bm[1]::int * 60 + bm[2]::int end;
  sla := case when tgl = td and menit <= bmenit then 'Tepat Waktu' else 'Terlambat' end;
  nw := jsonb_build_object('id', coalesce(cur.id, dco.next_id('DSO', '{}')), 'tanggal', tgl, 'toko', tk, 'form', p->>'form',
    'waktu_submit', nows, 'oleh', coalesce(nullif(p->>'oleh', ''), me->>'nama'), 'jawaban', jaw::text,
    'keterangan', coalesce(p->>'keterangan', ''), 'sla_submit', sla,
    'validasi', case when cur.validasi = 'Rejected' then '' else coalesce(cur.validasi, '') end,
    'validasi_oleh', case when cur.validasi = 'Rejected' then '' else coalesce(cur.validasi_oleh, '') end,
    'validasi_tgl', case when cur.validasi = 'Rejected' then '' else coalesce(cur.validasi_tgl, '') end,
    'ket_spv', coalesce(cur.ket_spv, ''),
    'sla_validasi', case when cur.validasi = 'Rejected' then '' else coalesce(cur.sla_validasi, '') end,
    'update_tgl', nows, 'update_oleh', me->>'nama');
  perform dco.upsert_row('dso', 'id', nw);
  return nw;
end $$;

-- DSO validasi SPV (dsoValidasi_) — SLA validasi dihitung server
create or replace function public.dco_dso_validate(p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); cur dco.dso; nw jsonb; v text;
begin
  perform dco.must_mgr(me);
  select * into cur from dco.dso where id = p->>'id' for update;
  if not found then raise exception 'Data tidak ditemukan'; end if;
  nw := to_jsonb(cur) - '_seq' - '_created';
  v := coalesce(dco.jtext(p->'validasi'), 'Approved');
  if p ? 'validasi' and v = '' then
    nw := nw || jsonb_build_object('validasi', '', 'validasi_oleh', '', 'validasi_tgl', '', 'sla_validasi', '');
  else
    nw := nw || jsonb_build_object('validasi', case when v = 'Rejected' then 'Rejected' else 'Approved' end,
      'validasi_oleh', me->>'nama', 'validasi_tgl', dco.now_s(), 'sla_validasi', dco.sla_validasi(cur.waktu_submit, now(), dco.cfg()));
  end if;
  if p ? 'ketSpv' and jsonb_typeof(p->'ketSpv') <> 'null' then nw := nw || jsonb_build_object('ket_spv', dco.jtext(p->'ketSpv')); end if;
  nw := nw || jsonb_build_object('update_tgl', dco.now_s(), 'update_oleh', me->>'nama');
  perform dco.upsert_row('dso', 'id', nw);
  return nw;
end $$;

-- DSO ubah sebagian tanpa submit ulang (dsoPatch_)
create or replace function public.dco_dso_patch(p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); is_mgr boolean := (me->>'is_mgr')::boolean; cur dco.dso; nw jsonb; jaw jsonb;
  item text := coalesce(p->>'itemId', ''); foto text := coalesce(p->>'fotoId', ''); old text; paths text[] := '{}';
begin
  select * into cur from dco.dso where id = p->>'id' for update;
  if not found then raise exception 'Laporan tidak ditemukan'; end if;
  if not is_mgr and cur.toko is distinct from me->>'toko' then raise exception 'Bukan laporan toko Anda'; end if;
  if cur.validasi = 'Approved' and not is_mgr then raise exception 'Sudah di-approve SPV, tidak bisa diubah'; end if;
  jaw := dco.safe_jsonb(cur.jawaban);
  if jsonb_typeof(jaw) <> 'object' then jaw := '{}'::jsonb; end if;
  if item <> '' then
    old := jaw->>item;
    if foto <> '' then
      if not dco.valid_photo(foto) then raise exception 'ID foto tidak valid'; end if;
      jaw := jaw || jsonb_build_object(item, foto);
    else
      jaw := jaw - item;
    end if;
    if old is not null and old is distinct from foto then paths := array[old]; end if;
  end if;
  nw := to_jsonb(cur) - '_seq' - '_created' || jsonb_build_object('jawaban', jaw::text);
  if p ? 'keterangan' and jsonb_typeof(p->'keterangan') <> 'null' then nw := nw || jsonb_build_object('keterangan', dco.jtext(p->'keterangan')); end if;
  if p ? 'oleh' and jsonb_typeof(p->'oleh') <> 'null' then nw := nw || jsonb_build_object('oleh', dco.jtext(p->'oleh')); end if;
  nw := nw || jsonb_build_object('update_tgl', dco.now_s(), 'update_oleh', me->>'nama');
  perform dco.upsert_row('dso', 'id', nw);
  return jsonb_build_object('row', nw, 'photos', to_jsonb(dco.grant_trash(paths)));
end $$;

-- ---------- USER & TOKO (userSave_, hapusUser_, gantiPin_, addToko_) ----------
create or replace function public.dco_user_save(p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); un text := lower(btrim(coalesce(p->>'username', ''))); rl text; tk text; cur dco.users; pin text := coalesce(dco.jtext(p->'pin'), '');
begin
  perform dco.must_master(me);
  if un = '' then raise exception 'Username wajib'; end if;
  rl := case when p->>'role' in ('MASTER','SPV') then p->>'role' else 'STORE' end;
  tk := case when rl = 'STORE' then coalesce(p->>'toko', '') else 'SEMUA' end;
  select * into cur from dco.users where lower(username) = un for update;
  if found then
    if cur.role = 'MASTER' and rl <> 'MASTER' and (select count(*) from dco.users where role = 'MASTER') <= 1 then
      raise exception 'Minimal harus ada satu akun Master'; end if;
    update dco.users set role = rl, toko = tk, nama = coalesce(nullif(p->>'nama', ''), un), email = coalesce(p->>'email', ''),
      pin_hash = case when pin <> '' then extensions.crypt(pin, extensions.gen_salt('bf', 8)) else pin_hash end,
      failed_count = case when pin <> '' then 0 else failed_count end, locked_until = case when pin <> '' then null else locked_until end
     where username = cur.username;
    if pin <> '' then   -- PIN direset Master: sesi lama user tsb (selain sesi ini) dicabut
      delete from dco.sessions where username = cur.username and token_hash <> encode(sha256(convert_to(p_token, 'UTF8')), 'hex');
    end if;
    return jsonb_build_object('ok', true, 'mode', 'update');
  end if;
  if pin = '' then raise exception 'PIN wajib untuk user baru'; end if;
  insert into dco.users(username, pin_hash, role, toko, nama, email)
  values (un, extensions.crypt(pin, extensions.gen_salt('bf', 8)), rl, tk, coalesce(nullif(p->>'nama', ''), un), coalesce(p->>'email', ''));
  return jsonb_build_object('ok', true, 'mode', 'baru');
end $$;

create or replace function public.dco_user_delete(p_token text, p_username text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); un text := lower(coalesce(p_username, ''));
begin
  perform dco.must_master(me);
  if un = lower(me->>'username') then raise exception 'Tidak bisa menghapus diri sendiri'; end if;
  if exists(select 1 from dco.users where lower(username) = un and role = 'MASTER') and (select count(*) from dco.users where role = 'MASTER') <= 1 then
    raise exception 'Minimal harus ada satu akun Master'; end if;
  delete from dco.users where lower(username) = un;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.dco_change_pin(p_token text, p_old text, p_new text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare me jsonb := dco.auth(p_token); u dco.users; tok text;
begin
  select * into u from dco.users where username = me->>'username' for update;
  if u.pin_hash <> extensions.crypt(coalesce(p_old, ''), u.pin_hash) then raise exception 'PIN lama salah'; end if;
  if coalesce(length(p_new), 0) < 4 then raise exception 'PIN baru minimal 4 digit'; end if;
  update dco.users set pin_hash = extensions.crypt(p_new, extensions.gen_salt('bf', 8)), failed_count = 0, locked_until = null where username = u.username;
  delete from dco.sessions where username = u.username;   -- semua perangkat lain otomatis keluar
  tok := dco.new_session(u.username);
  select * into u from dco.users where username = u.username;
  return dco.login_payload(u, tok);
end $$;

