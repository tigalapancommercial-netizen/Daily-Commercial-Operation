-- LOGIN (login_ Code.gs). Mengembalikan {ok,data|error} agar hitungan gagal tersimpan.
create or replace function public.dco_login(p_username text, p_pin text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare u dco.users; un text := lower(btrim(coalesce(p_username, ''))); tok text; mins int;
begin
  select * into u from dco.users where lower(username) = un for update;
  if not found or coalesce(p_pin, '') = '' then
    perform pg_sleep(0.25);
    return jsonb_build_object('ok', false, 'error', 'Username atau PIN salah');
  end if;
  if u.locked_until is not null and u.locked_until > now() then
    mins := greatest(1, ceil(extract(epoch from (u.locked_until - now())) / 60)::int);
    return jsonb_build_object('ok', false, 'error', 'Terlalu banyak percobaan PIN salah. Coba lagi dalam ' || mins || ' menit');
  end if;
  if u.pin_hash <> extensions.crypt(p_pin, u.pin_hash) then
    -- 5x salah berturut-turut -> akun dikunci 10 menit
    update dco.users set
      locked_until = case when failed_count + 1 >= 5 then now() + interval '10 minutes' else null end,
      failed_count = case when failed_count + 1 >= 5 then 0 else failed_count + 1 end
     where username = u.username;
    return jsonb_build_object('ok', false, 'error', 'Username atau PIN salah');
  end if;
  update dco.users set failed_count = 0, locked_until = null where username = u.username;
  tok := dco.new_session(u.username);
  return jsonb_build_object('ok', true, 'data', dco.login_payload(u, tok));
end $$;

