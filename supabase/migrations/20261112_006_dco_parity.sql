  coalesce(r->>'foto_id','') || ' ' || coalesce(r->>'foto','') || ' ' || coalesce(r->>'jawaban',''),
  '(\d{4}-\d{2}/[0-9a-f]{32}_[A-Za-z0-9]{4,16}\.(?:jpg|jpeg|png|webp))', 'g') m $$;
create or replace function dco.photo_referenced(p text) returns boolean language sql stable set search_path = pg_catalog, pg_temp as $$
select exists(select 1 from dco.masalah where foto_id = p) or exists(select 1 from dco.tugas where foto_id = p)
    or exists(select 1 from dco.ceklis where foto_id = p) or exists(select 1 from dco.visit_issue where foto_id = p)
    or exists(select 1 from dco.dso where strpos(jawaban, p) > 0) or exists(select 1 from dco.visit where strpos(foto, p) > 0) $$;
create or replace function dco.grant_trash(paths text[]) returns text[] language plpgsql set search_path = pg_catalog, pg_temp as $$
declare p text; outp text[] := '{}';
begin
  delete from dco.photo_trash where expires_at < now();
  foreach p in array coalesce(paths, '{}') loop
    if p is not null and not dco.photo_referenced(p) then
      insert into dco.photo_trash(name, expires_at) values (p, now() + interval '15 minutes')
        on conflict (name) do update set expires_at = excluded.expires_at;
      outp := outp || p;
    end if;
  end loop;
  return outp;
end $$;

-- SLA validasi (slaValidasi_ Code.gs): batas = submit + N jam; di luar jam kerja digeser ke jam mulai kerja berikutnya
create or replace function dco.sla_validasi(submit_s text, now_ts timestamptz, cfg jsonb) returns text language plpgsql stable set search_path = pg_catalog, pg_temp as $$
declare m text[]; sub timestamptz; addh numeric; sh int; eh int; due timestamptz; hh int; ymd date;
begin
  m := regexp_match(coalesce(submit_s,''), '^(\d{4})-(\d\d)-(\d\d)[ T](\d\d):(\d\d)(?::(\d\d))?');
  if m is null then return 'Data Waktu Tidak Valid'; end if;
  sub := make_timestamptz(m[1]::int, m[2]::int, m[3]::int, m[4]::int, m[5]::int, coalesce(m[6], '0')::double precision, 'Asia/Makassar');
  addh := coalesce(nullif(case when cfg->>'slaValidasiJam' ~ '^\s*-?\d+(\.\d+)?\s*$' then (cfg->>'slaValidasiJam')::numeric end, 0), 3);
  addh := greatest(1, addh);
  sh := coalesce(nullif(case when cfg->>'jamKerjaMulai' ~ '^\s*\d+(\.\d+)?\s*$' then floor((cfg->>'jamKerjaMulai')::numeric)::int end, 0), 8);
  eh := coalesce(nullif(case when cfg->>'jamKerjaSelesai' ~ '^\s*\d+(\.\d+)?\s*$' then floor((cfg->>'jamKerjaSelesai')::numeric)::int end, 0), 21);
  due := sub + addh * interval '1 hour';
  hh := extract(hour from (due at time zone 'Asia/Makassar'))::int;
  if hh >= eh or hh < sh then
    ymd := (due at time zone 'Asia/Makassar')::date;
    if hh >= eh then ymd := ymd + 1; end if;
    due := make_timestamptz(extract(year from ymd)::int, extract(month from ymd)::int, extract(day from ymd)::int, least(sh, 23), 0, 0, 'Asia/Makassar');
  end if;
  return case when now_ts <= due then 'Tepat Waktu' else 'Terlambat' end;
end $$;

