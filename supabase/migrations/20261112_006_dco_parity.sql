-- Nama tipe (tab) -> tabel
create or replace function dco.tbl(t text) returns text language sql immutable set search_path = pg_catalog, pg_temp as $$
select case upper(coalesce(t,'')) when 'TOKO' then 'toko' when 'USERS' then 'users' when 'CONFIG' then 'config'
  when 'MASALAH' then 'masalah' when 'TUGAS' then 'tugas' when 'RUTIN' then 'rutin' when 'CEKLIS' then 'ceklis'
  when 'FORM_DEF' then 'form_def' when 'DSO' then 'dso' when 'VISIT_DEF' then 'visit_def' when 'JADWAL' then 'jadwal'
  when 'VISIT' then 'visit' when 'VISIT_ISSUE' then 'visit_issue' else null end $$;
-- Kolom data (tanpa kolom teknis berawalan _), urutan = urutan kolom spreadsheet
create or replace function dco.data_cols(tbl text) returns text[] language sql stable set search_path = pg_catalog, pg_temp as $$
select array_agg(a.attname::text order by a.attnum) from pg_attribute a
 where a.attrelid = ('dco.' || quote_ident(tbl))::regclass and a.attnum > 0 and not a.attisdropped and a.attname !~ '^_' $$;

-- Upsert generik satu baris jsonb (kolom kosong -> '')
create or replace function dco.upsert_row(tbl text, pk text, r jsonb) returns void language plpgsql set search_path = pg_catalog, pg_temp as $$
declare cols text[] := dco.data_cols(tbl); ins text; sel text; upd text;
begin
  select string_agg(quote_ident(c), ','), string_agg(format('coalesce(x.%I, %L)', c, ''), ','),
         string_agg(format('%I = excluded.%I', c, c), ',') filter (where c <> pk)
    into ins, sel, upd from unnest(cols) c;
  execute format('insert into dco.%I (%s) select %s from jsonb_populate_record(null::dco.%I, $1) x on conflict (%I) do update set %s',
                 tbl, ins, sel, tbl, pk, upd) using r;
end $$;

-- Nomor urut berikut (nextSeq_ / nextSeq2_ Code.gs) — dipanggil di dalam advisory lock tabel
create or replace function dco.next_id(t text, r jsonb) returns text language plpgsql set search_path = pg_catalog, pg_temp as $$
declare tbl text := dco.tbl(t); n bigint; pre text; w int; sk text;
begin
  if upper(t) = 'VISIT_DEF' then
    sk := coalesce(r->>'seksi', '');
    select coalesce(max(substr(id, length(sk) + 1)::bigint), 0) + 1 into n from dco.visit_def
     where sk <> '' and left(id, length(sk)) = sk and substr(id, length(sk) + 1) ~ '^\d{1,15}$';
    return sk || dco.pad(n, 2);
  end if;
  select p, wd into pre, w from (values ('MASALAH','MS-',5),('TUGAS','TG-',5),('CEKLIS','CK-',6),('RUTIN','RT-',4),('DSO','DS-',6),
    ('VISIT','VS-',5),('VISIT_ISSUE','VI-',6),('JADWAL','JD-',5),('FORM_DEF','FD-',3)) v(t2, p, wd) where t2 = upper(t);
  if pre is null then raise exception 'Tipe tanpa ID otomatis: %', t; end if;
  execute format('select coalesce(max((regexp_match(id, ''-(\d{1,15})$''))[1]::bigint), 0) + 1 from dco.%I', tbl) into n;
  return pre || dco.pad(n, w);
end $$;

-- Sesi: token acak (disimpan hash sha256), berlaku 30 hari (diperpanjang saat dipakai)
create or replace function dco.auth(p_token text) returns jsonb language plpgsql set search_path = pg_catalog, pg_temp as $$
declare s dco.sessions; u dco.users; h text;
begin
  if coalesce(p_token, '') = '' then raise exception 'Sesi habis, silakan login ulang'; end if;
  h := encode(sha256(convert_to(p_token, 'UTF8')), 'hex');
  select * into s from dco.sessions where token_hash = h;
  if not found or s.expires_at < now() then raise exception 'Sesi tidak valid, silakan login ulang'; end if;
  select * into u from dco.users where username = s.username;
  if not found then raise exception 'Sesi tidak valid, silakan login ulang'; end if;
  if s.last_seen < now() - interval '1 hour' then
    update dco.sessions set last_seen = now(), expires_at = now() + interval '30 days' where token_hash = h;
  end if;
  return jsonb_build_object('username', u.username, 'role', u.role,
    'toko', case when u.role = 'STORE' then u.toko else 'SEMUA' end,
    'nama', coalesce(nullif(u.nama, ''), u.username), 'email', u.email,
    'is_master', u.role = 'MASTER', 'is_mgr', u.role in ('MASTER','SPV'));
end $$;
create or replace function dco.must_mgr(me jsonb) returns void language plpgsql immutable set search_path = pg_catalog, pg_temp as $$
begin if not (me->>'is_mgr')::boolean then raise exception 'Hanya SPV Area / Master yang boleh melakukan ini'; end if; end $$;
create or replace function dco.must_master(me jsonb) returns void language plpgsql immutable set search_path = pg_catalog, pg_temp as $$
begin if not (me->>'is_master')::boolean then raise exception 'Hanya Master yang boleh melakukan ini'; end if; end $$;
create or replace function dco.new_session(p_username text) returns text language plpgsql set search_path = pg_catalog, pg_temp as $$
declare tok text := encode(extensions.gen_random_bytes(32), 'hex');
begin
  delete from dco.sessions where expires_at < now();
  insert into dco.sessions(token_hash, username, expires_at) values (encode(sha256(convert_to(tok, 'UTF8')), 'hex'), p_username, now() + interval '30 days');
  return tok;
end $$;
create or replace function dco.login_payload(u dco.users, tok text) returns jsonb language sql stable set search_path = pg_catalog, pg_temp as $$
select jsonb_build_object('token', tok, 'username', u.username, 'nama', coalesce(nullif(u.nama, ''), u.username), 'role', u.role,
  'toko', case when u.role = 'STORE' then u.toko else 'SEMUA' end) $$;
create or replace function dco.user_slug(n text) returns text language sql immutable set search_path = pg_catalog, pg_temp as $$
select regexp_replace(regexp_replace(regexp_replace(lower(n), 'tigalapankaos ', 'tk-'), 'mamu ', 'mamu-'), '\s+', '-', 'g') $$;

-- Foto: ambil path Storage dari isi baris; cek masih dipakai; beri izin hapus berbatas waktu
create or replace function dco.photo_paths(r jsonb) returns text[] language sql immutable set search_path = pg_catalog, pg_temp as $$
